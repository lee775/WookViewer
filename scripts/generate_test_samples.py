# 3) PPTX (12 slides for natural-sort regression)
# ============================================================
def make_pptx(path: Path) -> None:
    slide_titles = [
        "1: 첫 번째 슬라이드",
        "2: 두 번째 슬라이드",
        "3: 표 테스트",
        "4: 다중 텍스트 박스",
        "5: 영문/한글 혼합 — Mixed",
        "6: 특수문자 < & >",
        "7: 일곱 번째",
        "8: 여덟 번째",
        "9: 아홉 번째",
        "10: 열 번째 (이 슬라이드가 slide2 뒤에 와야 함!)",
        "11: 열한 번째",
        "12: 마지막 — 자연수 정렬 OK",
    ]

    n = len(slide_titles)

    content_types_parts = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">',
        '  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>',
        '  <Default Extension="xml" ContentType="application/xml"/>',
        '  <Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>',
    ]
    for i in range(1, n + 1):
        content_types_parts.append(
            f'  <Override PartName="/ppt/slides/slide{i}.xml" '
            f'ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>'
        )
    content_types_parts.append("</Types>")
    content_types = "\n".join(content_types_parts)

    rels = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/>
</Relationships>"""

    presentation = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:presentation xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"/>"""

    def slide_xml(body: str) -> str:
        return f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main"
       xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"
       xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <p:cSld>
    <p:spTree>
{body}
    </p:spTree>
  </p:cSld>
</p:sld>"""

    def title_sp(text: str) -> str:
        safe = html.escape(text, quote=True)
        return f"      <p:sp><p:txBody><a:p><a:r><a:t>{safe}</a:t></a:r></a:p></p:txBody></p:sp>"

    def text_sp(text: str) -> str:
        safe = html.escape(text, quote=True)
        return f"      <p:sp><p:txBody><a:p><a:r><a:t>{safe}</a:t></a:r></a:p></p:txBody></p:sp>"

    def table_block() -> str:
        return """      <a:tbl>
        <a:tr>
          <a:tc><a:txBody><a:p><a:r><a:t>항목</a:t></a:r></a:p></a:txBody></a:tc>
          <a:tc><a:txBody><a:p><a:r><a:t>값</a:t></a:r></a:p></a:txBody></a:tc>
        </a:tr>
        <a:tr>
          <a:tc><a:txBody><a:p><a:r><a:t>가</a:t></a:r></a:p></a:txBody></a:tc>
          <a:tc><a:txBody><a:p><a:r><a:t>123</a:t></a:r></a:p></a:txBody></a:tc>
        </a:tr>
        <a:tr>
          <a:tc><a:txBody><a:p><a:r><a:t>나</a:t></a:r></a:p></a:txBody></a:tc>
          <a:tc><a:txBody><a:p><a:r><a:t>456</a:t></a:r></a:p></a:txBody></a:tc>
        </a:tr>
      </a:tbl>"""

    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", content_types)
        z.writestr("_rels/.rels", rels)
        z.writestr("ppt/presentation.xml", presentation)

        for i, title in enumerate(slide_titles, start=1):
            if i == 3:
                # 표 슬라이드
                body = "\n".join([title_sp(title), table_block()])
            elif i == 4:
                # 다중 텍스트 박스
                body = "\n".join([
                    title_sp(title),
                    text_sp("제목 박스"),
                    text_sp("본문 박스 1 — 여러 텍스트박스가 줄바꿈으로 구분됩니다."),
                    text_sp("본문 박스 2 — 두 번째 박스의 내용입니다."),
                ])
            elif i == 6:
                # 특수문자 — helper에서 자동 이스케이프됨
                body = "\n".join([
                    title_sp(title),
                    text_sp('XML 엔티티 디코딩 — <tag> & "quote"'),
                ])
            else:
                # 일반 텍스트
                body = "\n".join([
                    title_sp(title),
                    text_sp("이 슬라이드는 자연수 정렬을 검증합니다."),
                ])
            z.writestr(f"ppt/slides/slide{i}.xml", slide_xml(body))

    print(f"  PPTX -> {path.name}  ({path.stat().st_size:,} bytes)")


# ============================================================
def main() -> int:
    print(f"Output: {OUT_DIR}")
    print()
    make_pdf(OUT_DIR / "WookViewer-test.pdf")
    make_docx(OUT_DIR / "WookViewer-test.docx")
    make_pptx(OUT_DIR / "WookViewer-test.pptx")
    print()
    print(f"Done. Files in: {OUT_DIR}")
    for f in sorted(OUT_DIR.iterdir()):
        if f.is_file():
            print(f"  {f.name:40s}  {f.stat().st_size:>10,} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
