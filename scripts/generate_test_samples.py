# ============================================================
# 1) PDF
# ============================================================
def make_pdf(path: Path) -> None:
    """최소 PDF-1.4 — 2페이지, 내장 Helvetica 폰트, 영문 텍스트."""
    out = bytearray()
    offsets: dict[int, int] = {}

    def emit(s: bytes | str) -> None:
        if isinstance(s, str):
            s = s.encode("ascii")
        out.extend(s)

    def pos() -> int:
        return len(out)

    # Header
    emit(b"%PDF-1.4\n%\xE2\xE3\xCF\xD3\n")

    # Object 1: Catalog
    offsets[1] = pos()
    emit("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n")

    # Object 2: Pages
    offsets[2] = pos()
    emit("2 0 obj\n<< /Type /Pages /Kids [3 0 R 4 0 R] /Count 2 >>\nendobj\n")

    # Object 3: Page 1
    offsets[3] = pos()
    emit(
        "3 0 obj\n"
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        "/Resources << /Font << /F1 5 0 R >> >> /Contents 6 0 R >>\n"
        "endobj\n"
    )

    # Object 4: Page 2
    offsets[4] = pos()
    emit(
        "4 0 obj\n"
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        "/Resources << /Font << /F1 5 0 R >> >> /Contents 7 0 R >>\n"
        "endobj\n"
    )

    # Object 5: Helvetica (built-in standard font)
    offsets[5] = pos()
    emit("5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n")

    # Object 6: Page 1 content
    page1 = (
        "BT /F1 28 Tf 60 720 Td (WookViewer Test PDF) Tj ET\n"
        "BT /F1 14 Tf 60 680 Td (Page 1 of 2) Tj ET\n"
        "BT /F1 14 Tf 60 640 Td (This sample verifies:) Tj ET\n"
        "BT /F1 12 Tf 80 610 Td (- Page navigation \\(prev / next\\)) Tj ET\n"
        "BT /F1 12 Tf 80 590 Td (- Pinch zoom 1x to 5x) Tj ET\n"
        "BT /F1 12 Tf 80 570 Td (- Pan after zoom) Tj ET\n"
        "BT /F1 12 Tf 80 550 Td (- No banner \\(PDF is FULL fidelity\\)) Tj ET\n"
        "BT /F1 10 Tf 60 100 Td (Generated by generate_test_samples.py) Tj ET\n"
    ).encode("ascii")
    offsets[6] = pos()
    emit(f"6 0 obj\n<< /Length {len(page1)} >>\nstream\n")
    emit(page1)
    emit("\nendstream\nendobj\n")

    # Object 7: Page 2 content
    page2 = (
        "BT /F1 28 Tf 60 720 Td (WookViewer Test PDF) Tj ET\n"
        "BT /F1 14 Tf 60 680 Td (Page 2 of 2) Tj ET\n"
        "BT /F1 14 Tf 60 640 Td (Tap left arrow to go back to Page 1.) Tj ET\n"
        "BT /F1 12 Tf 60 580 Td (For Korean rendering, use the DOCX sample) Tj ET\n"
        "BT /F1 12 Tf 60 560 Td (\\(PDF Korean needs font embedding - out of scope\\).) Tj ET\n"
    ).encode("ascii")
    offsets[7] = pos()
    emit(f"7 0 obj\n<< /Length {len(page2)} >>\nstream\n")
    emit(page2)
    emit("\nendstream\nendobj\n")

    # xref table
    xref_start = pos()
    emit("xref\n0 8\n0000000000 65535 f \n")
    for i in range(1, 8):
        emit(f"{offsets[i]:010d} 00000 n \n")

    # Trailer
    emit("trailer\n<< /Size 8 /Root 1 0 R >>\nstartxref\n")
    emit(str(xref_start) + "\n%%EOF\n")

    path.write_bytes(out)
    print(f"  PDF  -> {path.name}  ({len(out):,} bytes)")


